// Codex has no buttons, so each custom button (and each favourite prompt) becomes a Codex
// skill, used as $ccb-<name> (docs/platforms/codex.md). Skills live in
// $CODEX_HOME/skills/<name>/SKILL.md; every file written here carries a marker, and only
// marked folders are ever rewritten or removed.
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { mkdir, readdir, realpath, rm, rmdir } from "node:fs/promises";

import { askFields, expand, hash, live, slugify, type Button, type Library, type Prompt } from "@ccb/core";

import { readText, writeFileAtomic } from "./fsutil.js";

export const CODEX_MARKER = "<!-- generated by claude-codex-buttons: change this in the Prompt Bank; edits here are replaced -->";

/** Skills the Codex plugin itself ships; generated names never take these. */
const RESERVED = new Set(["continue", "regenerate-prompt", "prompt-bank", "notes", "drive-sync", "translate"]);

/** Built-ins Codex can't know when the skill was written: described for the model instead. */
const BUILT_IN_WORDS: Record<string, string> = {
  selection: "(the text the user selected or pasted)",
  draft: "(the user's draft)",
  last_prompt: "(the user's previous message)",
  date: "(today's date)",
  time: "(the current time)",
  cwd: "(the current working directory)",
};

/** Cuts to at most `n` characters without splitting an emoji (a lone surrogate breaks YAML). */
function cut(s: string, n: number): string {
  const chars = Array.from(s);
  return chars.length <= n ? s : chars.slice(0, n).join("");
}

/** Which library wrote a skill: a hash of its data folder, so two libraries never remove each other's skills. */
function ownerTag(owner: string): string {
  return `<!-- ccb-library: ${hash(owner).slice(0, 12)} -->`;
}

/**
 * True when the Codex plugin prompt-buttons-codex is installed and not turned off in this
 * Codex home: its config.toml section, when there is one, decides; else the plugin cache.
 */
export async function codexPluginInstalled(home: string): Promise<boolean> {
  const config = (await readText(join(home, "config.toml"))) ?? "";
  const section = /^\s*\[plugins\."prompt-buttons-codex@[^"]*"\]\s*$([\s\S]*?)(?=^\s*\[|$(?![\s\S]))/m.exec(config);
  if (section) return !/^\s*enabled\s*=\s*false\b/m.test(section[1] ?? "");
  return (await readdir(join(home, "plugins", "cache", "ccb-codex")).catch(() => null)) !== null;
}

/** The library's data folder as one canonical path, so the same library always has the same tag. */
async function canonical(owner: string): Promise<string> {
  if (!owner) return "";
  const absolute = resolve(owner);
  return realpath(absolute).catch(() => absolute);
}

/** $CODEX_HOME, else ~/.codex. */
export function codexHome(env: NodeJS.ProcessEnv = process.env): string {
  return env["CODEX_HOME"]?.trim() || join(homedir(), ".codex");
}

export interface CodexSkill {
  /** The skill's name and folder, e.g. "ccb-plan-my-day". */
  name: string;
  content: string;
}

function variables(library: Library): Record<string, string> {
  return Object.fromEntries(live(library.variables).map((v) => [v.id, v.value]));
}

/** YAML double-quoted scalar on one line. */
function yamlString(s: string): string {
  return JSON.stringify(s.replace(/\s+/g, " ").trim());
}

function skillFor(name: string, title: string, template: string, library: Library, origin: string, owner: string): CodexSkill {
  const asks = askFields(template);
  // Codex doesn't substitute $1 or $ARGUMENTS in skills (X5), so each value the user must
  // give is named in the text and the model fills it in from what the user wrote.
  const answers = Object.fromEntries(asks.map((a, i) => [a.name, `<value ${i + 1}: ${a.name}>`]));
  const { text } = expand(template, { variables: variables(library), builtIns: BUILT_IN_WORDS, answers });
  const args = asks.map((a, i) => `value ${i + 1} = ${a.name}${a.default ? ` (default: ${a.default})` : ""}`).join(", ");
  const description = cut(`${title}: from your Prompt Bank (Claude Codex Custom Buttons).${args ? ` Asks for: ${args}.` : ""}`, 1000);
  const content = `---
name: ${name}
description: ${yamlString(description)}
metadata:
  short-description: ${yamlString(cut(title, 80))}
---
${CODEX_MARKER}
${ownerTag(owner)}
<!-- ${origin} -->

Treat the text below as the user's request and carry it out.${asks.length ? " Replace each <value N: name> with what the user gave after the skill's name, in order; use the default if one is listed, and ask for any that are missing." : ""} Anything else the user wrote after the skill's name is part of the request too.

${text}
`;
  return { name, content };
}

function baseName(raw: string): string {
  return `ccb-${slugify(raw).slice(0, 56).replace(/-+$/, "") || "prompt"}`;
}

/**
 * The skills for this library: one per submit/fill button (its prompt or text), then one
 * per favourite prompt not already used by a button. Names are unique and never reserved.
 */
export function codexSkills(library: Library, owner = ""): CodexSkill[] {
  const prompts = new Map(live(library.prompts).map((p) => [p.id, p]));
  const used = new Set<string>();
  const unique = (raw: string, fallbackSuffix: string): string => {
    let name = baseName(raw);
    if (RESERVED.has(name.slice(4)) || used.has(name)) name = `${name.slice(0, 55)}-${fallbackSuffix.slice(-8).toLowerCase()}`;
    used.add(name);
    return name;
  };
  const out: CodexSkill[] = [];
  const covered = new Set<string>();
  const buttons = [...live(library.buttons)].sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
  for (const b of buttons as Button[]) {
    const a = b.action;
    if (a.type !== "submit" && a.type !== "fill") continue;
    let template: string;
    let title = b.label;
    if ("promptId" in a) {
      const p = prompts.get(a.promptId);
      if (!p) continue; // its prompt was deleted
      template = p.body;
      title = `${b.label} (${p.title})`;
      covered.add(p.id);
    } else template = a.text;
    const name = unique(b.id.replace(/^btn_/, ""), b.id);
    out.push(skillFor(name, title, template, library, `button ${b.id}`, owner));
  }
  const favourites = [...prompts.values()].filter((p) => p.favorite && !covered.has(p.id)).sort((x, y) => x.createdAt.localeCompare(y.createdAt) || x.id.localeCompare(y.id));
  for (const p of favourites as Prompt[]) out.push(skillFor(unique(p.title, p.id), p.title, p.body, library, `prompt ${p.id}`, owner));
  return out;
}

/**
 * Writes the skills into $CODEX_HOME/skills and removes this library's generated skills
 * that no longer exist. Files without the marker, and skills another library wrote, are
 * never touched; only the SKILL.md is removed (and the folder, if then empty). With
 * `onlyIfInstalled`, does nothing unless the Codex plugin prompt-buttons-codex is installed.
 * `owner` is the library's data folder.
 */
export async function writeCodexSkills(
  library: Library,
  opts: { home?: string; onlyIfInstalled?: boolean; owner?: string } = {},
): Promise<{ written: string[]; removed: string[]; skipped: boolean }> {
  const home = opts.home ?? codexHome();
  if (opts.onlyIfInstalled && !(await codexPluginInstalled(home))) return { written: [], removed: [], skipped: true };
  const owner = await canonical(opts.owner ?? "");
  const tag = ownerTag(owner);
  // Skills written before libraries were tagged belong to whichever library meets them first.
  const ours = (text: string) => text.includes(CODEX_MARKER) && (text.includes(tag) || !text.includes("<!-- ccb-library:"));
  const dir = join(home, "skills");
  await mkdir(dir, { recursive: true });
  const skills = codexSkills(library, owner);
  const wanted = new Set(skills.map((s) => s.name));
  const written: string[] = [];
  for (const s of skills) {
    const path = join(dir, s.name, "SKILL.md");
    const existing = await readText(path);
    if (existing !== null && !ours(existing)) continue; // the user's own, or another library's
    if (existing === s.content) continue;
    await mkdir(join(dir, s.name), { recursive: true });
    await writeFileAtomic(path, s.content, 0o644);
    written.push(s.name);
  }
  const removed: string[] = [];
  for (const name of await readdir(dir).catch(() => [] as string[])) {
    if (!name.startsWith("ccb-") || wanted.has(name)) continue;
    const text = await readText(join(dir, name, "SKILL.md"));
    if (text === null || !ours(text)) continue;
    await rm(join(dir, name, "SKILL.md"), { force: true });
    await rmdir(join(dir, name)).catch(() => undefined); // left in place if the user added files
    removed.push(name);
  }
  return { written, removed, skipped: false };
}
