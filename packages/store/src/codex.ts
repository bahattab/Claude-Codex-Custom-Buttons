// Codex has no buttons, so each custom button (and each favourite prompt) becomes a Codex
// skill, used as $ccb-<name> (docs/platforms/codex.md). Skills live in
// $CODEX_HOME/skills/<name>/SKILL.md; every file written here carries a marker, and only
// marked folders are ever rewritten or removed.
import { homedir } from "node:os";
import { join } from "node:path";
import { mkdir, readdir, rm } from "node:fs/promises";

import { askFields, expand, live, slugify, type Button, type Library, type Prompt } from "@ccb/core";

import { readText, writeFileAtomic } from "./fsutil.js";

export const CODEX_MARKER = "<!-- generated by claude-codex-buttons: change this in the Prompt Bank; edits here are replaced -->";

/** Skills the Codex plugin itself ships; generated names never take these. */
const RESERVED = new Set(["continue", "regenerate-prompt", "prompt-bank", "notes", "drive-sync"]);

/** Built-ins Codex can't know when the skill was written: described for the model instead. */
const BUILT_IN_WORDS: Record<string, string> = {
  selection: "(the text the user selected or pasted)",
  draft: "(the user's draft)",
  last_prompt: "(the user's previous message)",
  date: "(today's date)",
  time: "(the current time)",
  cwd: "(the current working directory)",
};

/** $CODEX_HOME, else ~/.codex. */
export function codexHome(env: NodeJS.ProcessEnv = process.env): string {
  return env["CODEX_HOME"]?.trim() || join(homedir(), ".codex");
}

export interface CodexSkill {
  /** The skill's name and folder, e.g. "ccb-plan-my-day". */
  name: string;
  content: string;
}

function variables(library: Library): Record<string, string> {
  return Object.fromEntries(live(library.variables).map((v) => [v.id, v.value]));
}

/** YAML double-quoted scalar on one line. */
function yamlString(s: string): string {
  return JSON.stringify(s.replace(/\s+/g, " ").trim());
}

function skillFor(name: string, title: string, template: string, library: Library, origin: string): CodexSkill {
  const asks = askFields(template);
  const answers = Object.fromEntries(asks.map((a, i) => [a.name, `$${i + 1}`]));
  const { text } = expand(template, { variables: variables(library), builtIns: BUILT_IN_WORDS, answers });
  const args = asks.map((a, i) => `$${i + 1} = ${a.name}${a.default ? ` (default: ${a.default})` : ""}`).join(", ");
  const description = `${title}: from your Prompt Bank (Claude Codex Custom Buttons).${args ? ` Arguments: ${args}.` : ""}`.slice(0, 1000);
  const content = `---
name: ${name}
description: ${yamlString(description)}
metadata:
  short-description: ${yamlString(title.slice(0, 80))}
---
${CODEX_MARKER}
<!-- ${origin} -->

Treat the text below as the user's request and carry it out.${asks.length ? " Where it shows $1, $2 and so on, use the values the user gave after the skill's name, in order; ask for any that are missing." : ""}

${text}

Anything else the user wrote after the skill's name: $ARGUMENTS
`;
  return { name, content };
}

function baseName(raw: string): string {
  return `ccb-${slugify(raw).slice(0, 56).replace(/-+$/, "") || "prompt"}`;
}

/**
 * The skills for this library: one per submit/fill button (its prompt or text), then one
 * per favourite prompt not already used by a button. Names are unique and never reserved.
 */
export function codexSkills(library: Library): CodexSkill[] {
  const prompts = new Map(live(library.prompts).map((p) => [p.id, p]));
  const used = new Set<string>();
  const unique = (raw: string, fallbackSuffix: string): string => {
    let name = baseName(raw);
    if (RESERVED.has(name.slice(4)) || used.has(name)) name = `${name.slice(0, 55)}-${fallbackSuffix.slice(-8).toLowerCase()}`;
    used.add(name);
    return name;
  };
  const out: CodexSkill[] = [];
  const covered = new Set<string>();
  const buttons = [...live(library.buttons)].sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
  for (const b of buttons as Button[]) {
    const a = b.action;
    if (a.type !== "submit" && a.type !== "fill") continue;
    let template: string;
    let title = b.label;
    if ("promptId" in a) {
      const p = prompts.get(a.promptId);
      if (!p) continue; // its prompt was deleted
      template = p.body;
      title = `${b.label} (${p.title})`;
      covered.add(p.id);
    } else template = a.text;
    const name = unique(b.id.replace(/^btn_/, ""), b.id);
    out.push(skillFor(name, title, template, library, `button ${b.id}`));
  }
  const favourites = [...prompts.values()].filter((p) => p.favorite && !covered.has(p.id)).sort((x, y) => x.createdAt.localeCompare(y.createdAt) || x.id.localeCompare(y.id));
  for (const p of favourites as Prompt[]) out.push(skillFor(unique(p.title, p.id), p.title, p.body, library, `prompt ${p.id}`));
  return out;
}

/**
 * Writes the skills into $CODEX_HOME/skills and removes generated skills that no longer
 * exist. Folders without the marker are never touched. With `onlyIfInstalled`, does
 * nothing when the Codex folder doesn't exist (Codex isn't used on this computer).
 */
export async function writeCodexSkills(
  library: Library,
  opts: { home?: string; onlyIfInstalled?: boolean } = {},
): Promise<{ written: string[]; removed: string[]; skipped: boolean }> {
  const home = opts.home ?? codexHome();
  if (opts.onlyIfInstalled && (await readdir(home).catch(() => null)) === null) return { written: [], removed: [], skipped: true };
  const dir = join(home, "skills");
  await mkdir(dir, { recursive: true });
  const skills = codexSkills(library);
  const wanted = new Set(skills.map((s) => s.name));
  const written: string[] = [];
  for (const s of skills) {
    const path = join(dir, s.name, "SKILL.md");
    const existing = await readText(path);
    if (existing !== null && !existing.includes(CODEX_MARKER)) continue; // the user's own skill with that name
    if (existing === s.content) continue;
    await mkdir(join(dir, s.name), { recursive: true });
    await writeFileAtomic(path, s.content, 0o644);
    written.push(s.name);
  }
  const removed: string[] = [];
  for (const name of await readdir(dir).catch(() => [] as string[])) {
    if (!name.startsWith("ccb-") || wanted.has(name)) continue;
    const text = await readText(join(dir, name, "SKILL.md"));
    if (text === null || !text.includes(CODEX_MARKER)) continue;
    await rm(join(dir, name), { recursive: true, force: true });
    removed.push(name);
  }
  return { written, removed, skipped: false };
}
